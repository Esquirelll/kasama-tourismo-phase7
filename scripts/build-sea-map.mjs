// One-off: turns Natural Earth (world-atlas 50m, public domain) into small SVG paths for Southeast Asia.
// Run: node scripts/build-sea-map.mjs  ->  writes src/geo/seaMap.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoArea, geoCentroid, geoGraticule10, geoMercator, geoPath } from 'd3-geo'

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'))
const all = feature(topo, topo.objects.countries).features
const WANT = {
  '096': ['brunei', 'Brunei'], '104': ['myanmar', 'Myanmar'], '116': ['cambodia', 'Cambodia'],
  '360': ['indonesia', 'Indonesia'], '418': ['laos', 'Laos'], '458': ['malaysia', 'Malaysia'],
  '608': ['philippines', 'Philippines'], '626': ['timor-leste', 'Timor-Leste'], '702': ['singapore', 'Singapore'],
  '704': ['vietnam', 'Vietnam'], '764': ['thailand', 'Thailand'],
}
const feats = all.filter((f) => WANT[String(f.id).padStart(3, '0')])
const collection = { type: 'FeatureCollection', features: feats }
const W = 1000
const projection = geoMercator().fitWidth(W, collection)
const path = geoPath(projection).digits(1)
const [[, y0], [, y1]] = path.bounds(collection)
const H = Math.ceil(y1 + 12)
projection.translate([projection.translate()[0], projection.translate()[1] + 6])
const p2 = geoPath(projection).digits(1)

const countries = feats.map((f) => {
  const [id, name] = WANT[String(f.id).padStart(3, '0')]
  // label point = centroid of the biggest piece (so islands do not pull it into the sea)
  let target = f
  if (f.geometry.type === 'MultiPolygon') {
    let best = null, bestA = -1
    for (const coords of f.geometry.coordinates) {
      const poly = { type: 'Polygon', coordinates: coords }
      const a = geoArea(poly)
      if (a > bestA) { bestA = a; best = poly }
    }
    target = { type: 'Feature', geometry: best }
  }
  const [lx, ly] = projection(geoCentroid(target))
  const [[bx0, by0], [bx1, by1]] = p2.bounds(f)
  return { id, name, d: p2(f), label: [Math.round(lx), Math.round(ly)], bounds: [bx0, by0, bx1, by1].map((n) => Math.round(n)) }
})
// light graticule, clipped to the map frame
const grat = p2(geoGraticule10()) ?? ''
const out = `// GENERATED by scripts/build-sea-map.mjs from Natural Earth (public domain). Do not edit by hand.
export const SEA_VIEWBOX = { w: ${W}, h: ${H} }
export const SEA_GRATICULE = ${JSON.stringify(grat)}
export const SEA_COUNTRIES = ${JSON.stringify(countries)} as {
  id: string; name: string; d: string; label: [number, number]; bounds: [number, number, number, number]
}[]
`
writeFileSync('src/geo/seaMap.ts', out)
console.log('countries', countries.length, 'viewBox', W, H, 'bytes', out.length)
